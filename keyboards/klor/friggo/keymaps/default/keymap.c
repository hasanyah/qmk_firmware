void haptic_buzz(layer_state_t state) {
    switch (get_highest_layer(state)) {
        case 0:
            break;
        case 1:
            drv2605l_pulse(DRV2605L_EFFECT_SHARP_CLICK_60);
            break;
        case 2:
            drv2605l_pulse(DRV2605L_EFFECT_DOUBLE_CLICK_60);
            break;
        default:
            drv2605l_pulse(DRV2605L_EFFECT_SOFT_BUMP_30);
            break;
    }
}

static bool scrolling_mode = false;
int layerstate = 0;
layer_state_t layer_state_set_user(layer_state_t state) {
    static layer_state_t old_state = 0;

#ifdef HAPTIC_ENABLE
    if (state != old_state) {
        haptic_buzz(state);
    }
#endif // HAPTIC_ENABLE

    old_state = state;
    switch (get_highest_layer(state)) {
        case 0:
            strcpy ( layer_state_str, "BASS");
            scrolling_mode = false;
            break;
        case 1:
            strcpy ( layer_state_str, "SYM1");
            scrolling_mode = false;
            break;
        case 2:
            strcpy ( layer_state_str, "SYM2");
            scrolling_mode = false;
            break;
        case 3:
            strcpy ( layer_state_str, "NUM");
            scrolling_mode = false;
            break;
        case 4:
            strcpy ( layer_state_str, "FUN");
            scrolling_mode = false;
            break;
        case 5:
            strcpy ( layer_state_str, "NAV");
            scrolling_mode = true;
            break;
        case 6:
            strcpy ( layer_state_str, "GAME");
            scrolling_mode = false;
            break;
        case 7:
            strcpy ( layer_state_str, "MOUSE");
            scrolling_mode = false;
            break;
        default:
            strcpy ( layer_state_str, "XXXXXX");
    }

    return state;
}

